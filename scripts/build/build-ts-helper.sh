#!/usr/bin/env bash
# Generate the development pin BEFORE Swift compilation. No runtime sidecar.
set -euo pipefail
export GIT_TERMINAL_PROMPT=0 GIT_CONFIG_COUNT=1 GIT_CONFIG_KEY_0=credential.helper GIT_CONFIG_VALUE_0=
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
cd "$ROOT"
PIN="Packages/OsaurusCore/Services/PhoneAccess/PhoneAccessBuildPin.swift"
mkdir -p build
VALUE=nil
if command -v go >/dev/null 2>&1; then
    (cd helpers/osaurus-ts && go build -trimpath -o ../../build/osaurus-ts .)
    # Default is ad-hoc and never accesses the login keychain. Distribution
    # builders may explicitly supply the same signing identity as the app.
    codesign --force --sign "${TS_HELPER_SIGN_IDENTITY:--}" build/osaurus-ts
    DIGEST="$(shasum -a 256 build/osaurus-ts | awk '{print $1}')"
    VALUE="\"$DIGEST\""
else
    echo "Go not found; skipping osaurus-ts. Phone access will be unavailable."
    rm -f build/osaurus-ts
fi
# Remove obsolete sidecars so they cannot be mistaken for the trust source.
rm -f build/osaurus-ts.sha256
cat > build/PhoneAccessBuildPin.swift <<SWIFT
// Generated by scripts/build/build-ts-helper.sh before compiling the app.
// The checked-in nil value fails closed for unprepared ad-hoc builds.
enum PhoneAccessBuildPin {
    static let sha256: String? = $VALUE
}
SWIFT
if ! cmp -s build/PhoneAccessBuildPin.swift "$PIN"; then
    cp build/PhoneAccessBuildPin.swift "$PIN"
fi
